def not_found_body() -> str:
    return """<h1>Page not found</h1>
<p>There is no page at this address.</p>
<ul>
<li><a href="/">Go to the home page</a></li>
<li><a href="/privacy/">Privacy and corrections</a></li>
</ul>"""


def placeholder_index_body() -> str:
    return f"""<h1>{SITE_NAME}</h1>
<p>Neutral, sourced public profiles of South Africa's elected representatives, starting with the City of Johannesburg councillors elected on 4 November 2026.</p>
<p><strong>Coming soon.</strong> Draft profiles are being reviewed before they appear here.</p>"""


def index_body(profiles: list[tuple[Path, dict[str, Any]]] | None) -> str:
    """Home page. CHG-PW-006 has no profile pages yet, so this is the labelled placeholder."""
    return placeholder_index_body()


def extra_pages(profiles: list[tuple[Path, dict[str, Any]]] | None) -> dict[str, tuple[str, str]]:
    """Pages beyond the fixed ones: {relative path: (title, body)}. None in CHG-PW-006."""
    return {}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_site(
    out: Path,
    *,
    profiles: list[tuple[Path, dict[str, Any]]] | None = None,
    commit: str | None = None,
    now: datetime | None = None,
) -> dict[str, Any]:
    """Write the static site into `out` (created; existing generated files overwritten)."""
    now = (now or datetime.now(timezone.utc)).astimezone(SAST)
    build_id = "B" + now.astimezone(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out.mkdir(parents=True, exist_ok=True)
    pages: dict[str, tuple[str, str]] = {
        "index.html": ("Home" if profiles else "Coming soon", index_body(profiles)),
        "privacy/index.html": ("Privacy and corrections", privacy_body()),
        "404.html": ("Page not found", not_found_body()),
    }
    pages.update(extra_pages(profiles))
    for rel, (title, body) in pages.items():
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        canonical = "/" + rel.removesuffix("index.html") if rel != "404.html" else "/404.html"
        target.write_text(page(title, body, canonical_path=canonical, build_id=build_id), encoding="utf-8")
    (out / "robots.txt").write_text(ROBOTS_TXT, encoding="utf-8")
    (out / "_config.yml").write_text(JEKYLL_CONFIG, encoding="utf-8")
    (out / "assets").mkdir(exist_ok=True)
    (out / "assets" / "site.css").write_text((ASSETS_DIR / "site.css").read_text(encoding="utf-8"), encoding="utf-8")
    (out / "favicon.svg").write_text((ASSETS_DIR / "favicon.svg").read_text(encoding="utf-8"), encoding="utf-8")
    files = sorted(p for p in out.rglob("*") if p.is_file() and p.name != "manifest.json" and ".git" not in p.parts)
    manifest = {
        "site": SITE_URL,
        "status": "draft",
        "build_id": build_id,
        "generated_at_sast": now.isoformat(timespec="seconds"),
        "commit": commit,
        "profiles": len(profiles or []),
        "pages": sorted(pages),
        "files": {str(p.relative_to(out)): _sha256(p) for p in files},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


class _PageScan(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.robots: list[str] = []
        self.csp: list[str] = []
        self.has_script = False
        self.draft_banner = False
        self.privacy_link = False
        self.in_draft = 0
        self.external_resources: list[str] = []
        self.text: list[str] = []
        self.hrefs: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        a = {k: (v or "") for k, v in attrs}
        if tag == "meta" and a.get("name", "").lower() == "robots":
            self.robots.append(a.get("content", ""))
        if tag == "meta" and a.get("http-equiv", "").lower() == "content-security-policy":
            self.csp.append(a.get("content", ""))
        if tag == "script":
            self.has_script = True
        if tag == "div" and "draft" in a.get("class", "").split():
            self.in_draft += 1
        if tag == "a":
            href = a.get("href", "")
            self.hrefs.append(href)
            if href == "/privacy/":
                self.privacy_link = True
        if tag in ("link", "img", "iframe", "object", "embed", "source", "video", "audio"):
            src = a.get("src") or (a.get("href") if tag == "link" else "")
            if src and re.match(r"^(https?:)?//", src) and not (tag == "link" and a.get("rel") == "canonical"):
                self.external_resources.append(src)

    def handle_endtag(self, tag: str) -> None:
        if tag == "div" and self.in_draft:
            self.in_draft -= 1

    def handle_data(self, data: str) -> None:
        self.text.append(data)
        if self.in_draft and DRAFT_MARK in data:
            self.draft_banner = True


def scan_html(html: str) -> _PageScan:
    s = _PageScan()
    s.feed(html)
    s.close()
    return s


def check_page(rel: str, html: str) -> list[str]:
    s = scan_html(html)
    fails = []
    if not any("noindex" in r and "nofollow" in r for r in s.robots):
        fails.append(f"{rel}: missing robots noindex, nofollow meta")
    if not s.csp or "default-src 'none'" not in s.csp[0]:
        fails.append(f"{rel}: missing the Content-Security-Policy meta (default-src 'none')")
    if s.has_script:
        fails.append(f"{rel}: has a <script> element")
    if not s.draft_banner:
        fails.append(f"{rel}: missing the visible DRAFT banner")
    if not s.privacy_link:
        fails.append(f"{rel}: missing the link to /privacy/")
    if not re.search(r"<title>DRAFT ", html):
        fails.append(f"{rel}: <title> does not start with DRAFT")
    for src in s.external_resources:
        fails.append(f"{rel}: loads an external resource {src}")
    text = " ".join(s.text) + " " + " ".join(s.hrefs)
    for m in EMAIL_RE.findall(text):
        if m.lower() != PRIVACY_EMAIL:
            fails.append(f"{rel}: e-mail address other than the role contact: {m}")
    if SA_PHONE_RE.search(" ".join(s.text)):
        fails.append(f"{rel}: text looks like an SA phone number")
    if SA_ID_RE.search(" ".join(s.text)):
        fails.append(f"{rel}: text has a 13-digit number (possible SA ID)")
    return fails


def check_site(out: Path) -> list[str]:
    """Fail-closed checks on a built site directory."""
    fails: list[str] = []
    robots = out / "robots.txt"
    if not robots.is_file() or robots.read_text(encoding="utf-8") != ROBOTS_TXT:
        fails.append("robots.txt is missing or is not exactly 'User-agent: * / Disallow: /'")
    if (out / "sitemap.xml").exists():
        fails.append("sitemap.xml must not exist while the site is a draft")
    privacy = out / "privacy" / "index.html"
    if not privacy.is_file():
        fails.append("privacy/index.html is missing")
    elif f"mailto:{PRIVACY_EMAIL}" not in privacy.read_text(encoding="utf-8"):
        fails.append(f"privacy page does not give the role contact {PRIVACY_EMAIL}")
    pages = sorted(out.rglob("*.html"))
    if not pages:
        fails.append("no HTML pages built")
    for p in pages:
        fails += check_page(str(p.relative_to(out)), p.read_text(encoding="utf-8"))
    allowed = {".html", ".css", ".svg", ".txt", ".json", ".yml"}
    for p in out.rglob("*"):
        if p.is_file() and ".git" not in p.parts and p.suffix not in allowed and p.name not in ("CNAME", "README.md"):
            fails.append(f"unexpected file type in site: {p.relative_to(out)}")
    return fails
