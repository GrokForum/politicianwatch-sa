"""Static draft site for politicianwatch.grokforum.site (CHG-PW-006).

`build_site` writes a plain static site (HTML + one CSS file, no scripts) into an output
directory. That directory is what a publish would copy into the public `politicianwatch-site`
repository; nothing here publishes anything.

Every page carries:
- the robots `noindex, nofollow` meta (robots.txt is `Disallow: /`);
- a visible DRAFT banner with a link to the privacy page;
- a meta Content-Security-Policy (no scripts, same-origin styles and images only).

GitHub Pages cannot set response headers, so an `X-Robots-Tag` header is not possible on this
host; robots.txt plus the per-page meta are the controls (recorded in the CHG-PW-006 RFC).

`check_site` re-reads a built directory and returns failures; `pwatch site check` exits 2 on any.
"""

from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timedelta, timezone
from html import escape
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

ASSETS_DIR = Path(__file__).resolve().parent / "site_assets"

SITE_NAME = "PoliticianWatch SA"
SITE_URL = "https://politicianwatch.grokforum.site"
PRIVACY_EMAIL = "privacy@grokforum.site"
RESPONSIBLE_PARTY = "GrokForum"
INFO_REGULATOR_URL = "https://inforegulator.org.za/"

ROBOTS_TXT = "User-agent: *\nDisallow: /\n"
ROBOTS_META = '<meta name="robots" content="noindex, nofollow">'
CSP = (
    "default-src 'none'; style-src 'self'; img-src 'self'; base-uri 'none'; "
    "form-action 'none'"
)
CSP_META = f'<meta http-equiv="Content-Security-Policy" content="{CSP}">'
DRAFT_MARK = "DRAFT."
DRAFT_BANNER = (
    '<div class="draft" role="note"><p><strong>DRAFT.</strong> This site is an unfinished draft. '
    "Profiles cover elected representatives' public role only. Every item shows an evidence label; "
    'every item except an Unknown one links a dated source. <a href="/privacy/">Privacy and corrections</a></p></div>'
)
# Jekyll (GitHub Pages "legacy" build) would otherwise turn README.md into a page without the
# noindex meta. HTML files without front matter are copied unchanged.
JEKYLL_CONFIG = "# Generated by pwatch site build (CHG-PW-006). Keep the repo README off the site.\nexclude:\n  - README.md\n"
SAST = timezone(timedelta(hours=2))

# Rough personal-information patterns for the fail-closed scan of built pages.
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
SA_PHONE_RE = re.compile(r"(?<!\d)(?:\+27|0)[1-8]\d(?:[ -]?\d){7}(?!\d)")
SA_ID_RE = re.compile(r"(?<!\d)\d{13}(?!\d)")


def page(title: str, body: str, *, canonical_path: str, build_id: str | None = None) -> str:
    """Full HTML page with the DRAFT banner, noindex meta, CSP and footer."""
    stamp = f" · Build {escape(build_id)}" if build_id else ""
    return "\n".join(
        [
            "<!doctype html>",
            '<html lang="en-ZA">',
            "<head>",
            '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            ROBOTS_META,
            CSP_META,
            '<meta name="referrer" content="no-referrer">',
            '<link rel="icon" href="/favicon.svg" type="image/svg+xml">',
            '<link rel="stylesheet" href="/assets/site.css">',
            f"<title>DRAFT · {escape(title)} · {SITE_NAME}</title>",
            f'<link rel="canonical" href="{SITE_URL}{canonical_path}">',
            "</head>",
            "<body>",
            '<a class="skip" href="#main">Skip to content</a>',
            DRAFT_BANNER,
            '<main id="main">',
            body,
            "</main>",
            f'<footer><p>{SITE_NAME} (draft) · <a href="/">Home</a> · '
            f'<a href="/privacy/">Privacy and corrections</a>{stamp}</p></footer>',
            "</body>",
            "</html>",
            "",
        ]
    )


